  assert.equal(await repo.authorizePreparation(checking),false,'definition change prevents dispatch');
  await service.request('verify_requirement.v1','r',token());
  const blocked=await repo.claim('interactive','blocked');assert(blocked);
  delete process.env.OPENROUTER_API_KEY;
  assert.equal(await repo.admitDispatch(blocked,DEFAULT_BUDGET),null);
  assert.equal((await db.query('SELECT attempt FROM analysis_jobs WHERE id=$1',[blocked.id])).rows[0].attempt,0,'configuration block does not consume claim attempts');
  const retried=await service.retry(blocked.id,token());
  assert.notEqual(retried.id,blocked.id,'explicit blocked retry creates a new job');
  assert.equal((await service.get(blocked.id)).state,'cancelled');
  await db.query("UPDATE analysis_jobs SET state='blocked',provider_attempts=3 WHERE id=$1",[retried.id]);
  await repo.recover();
  assert.equal((await service.get(retried.id!)).state,'dead_letter','exhausted blocked work becomes terminal');
  // Lender authority is independent throughout the real worker pipeline.
  process.env.OPENROUTER_API_KEY='synthetic-not-sent';
  process.env.ANALYSIS_DEBUG_CAPTURE='0';
  await db.query(`INSERT INTO "user"(id,name,email,"emailVerified") VALUES('l','Lender','lender@example.test',true)`);
  await db.query("INSERT INTO application_memberships(application_id,user_id,role) VALUES('a','l','lender')");
  const lender=new AnalysisService({applicationId:'a',userId:'l',role:'lender',displayName:'Lender'},db);
  const toggle=async(enabled:boolean)=>service.setPreference(enabled,(await service.status()).preference.epoch);
  await toggle(false);
  const off=(await service.status()).preference;
  await assert.rejects(lender.request('verify_requirement.v1','r',token()),{status:409},'unsent lender AI blocked');
  assert.deepEqual((await lender.status()).jobs,[],'draft jobs hidden from lender');
  await assert.rejects(lender.get(recovered.id),{status:404},'direct draft job ID hidden');
  const publish=async()=>db.query(`WITH package AS (SELECT a.*,build_submission_manifest(a.id) manifest FROM applications a WHERE id='a')
    INSERT INTO submissions(id,application_id,revision_number,source_application_revision,source_content_revision,submitted_by_user_id,submitted_by_label,manifest,canonical_manifest,manifest_sha256,idempotency_key,acknowledgment)
    SELECT $1,id,coalesce((SELECT max(revision_number) FROM submissions WHERE application_id='a'),0)+1,revision,content_revision,'u','Borrower',manifest,manifest::text,encode(sha256(convert_to(manifest::text,'UTF8')),'hex'),$1,'[]'::jsonb FROM package`,[token()]);
  await publish();
  const lenderRequest=await lender.request('verify_requirement.v1','r','lender-key');
  assert(lenderRequest.id);
  assert.deepEqual((await service.status()).preference,off,'lender enqueue preserves borrower preference');
  assert.equal((await lender.request('verify_requirement.v1','r','lender-key')).id,lenderRequest.id);
  assert.equal((await lender.get(lenderRequest.id)).consentScope,'lender');
  assert.equal((await service.get(lenderRequest.id)).canCancel,false);
  await assert.rejects(service.cancel(lenderRequest.id),{status:403});
  await lender.setPreference(true,'0');
  assert.deepEqual((await service.status()).preference,off,'lender personal toggle does not change borrower');
  await lender.setPreference(false,'1');
  await assert.rejects(lender.request('match_document.v1',doc,token()),{status:403});
  await assert.rejects(service.request('verify_requirement.v1','r',token()),{status:403});
  const lenderLease=await repo.claim('interactive','lender');assert(lenderLease);assert.equal(lenderLease.id,lenderRequest.id);
  const verified={schemaVersion:'verify.v1',requirementId:'r',assessment:'unknown',checks:[],missingEvidence:[],conflicts:[],limitations:[]};
  let calls=0;
  await runJob(lenderLease,{repository:repo,prepare:createAnalysisPreparer(repo.readEvidence.bind(repo)),budget:DEFAULT_BUDGET,transport:{generate:async()=>{
    calls++;
    assert.deepEqual((await service.status()).preference,off,'dispatch works with borrower off');
    await toggle(true);
    const borrowerJob=await service.request('verify_requirement.v1','r',token());
    assert.notEqual(borrowerJob.id,lenderLease.id,'dedup separates authorities');
    await assert.rejects(service.retry(lenderLease.id,token()),{status:404});
    await toggle(false);
    assert.equal((await service.get(borrowerJob.id!)).state,'cancelled');
    assert.equal((await lender.get(lenderLease.id)).state,'running');
    assert.equal(await repo.heartbeat(lenderLease),true);
    return {text:JSON.stringify(verified),usage:{inputTokens:100,outputTokens:100}};
  }}},new AbortController().signal);
  assert.equal(calls,1,'worker dispatched through simulated transport');
  assert.equal((await lender.get(lenderLease.id)).state,'succeeded');
  assert.equal((await lender.get(lenderLease.id)).freshness,'current');
