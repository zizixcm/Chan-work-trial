  await assert.rejects(lender.request('verify_requirement.v1','r','lender-key'),{status:409},'receipt cannot cross role boundary');
  // One user's preference follows them between applications, never other users.
  await db.query("INSERT INTO application_memberships(application_id,user_id,role) VALUES('b','u','borrower'),('a','v','borrower')");
  const sameUserOtherApp=new AnalysisService({...borrower,applicationId:'b'},db);
