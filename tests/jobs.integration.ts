  await db.query("INSERT INTO requirements(id,application_id,title,category,purpose,period,owner,applicability,sort_order) VALUES('r','a','Rent roll','Property','Evidence','Current','Borrower','Required',1)");
  await service.setPreference(true,'0');
  const doc=token();
  await portal.insertMany({id:doc,application_id:'a',original_name:'synthetic.csv',storage_key:doc,content_type:'text/csv; charset=utf-8',size_bytes:10,sha256:'a'.repeat(64),uploaded_by:'Synthetic',created_at:new Date().toISOString()},[]);
  assert.equal((await service.status()).jobs.length,1,'upload atomically queues supported MIME');
  const requests=await Promise.all([service.request('match_document.v1',doc,'same-key'),service.request('match_document.v1',doc,'same-key')]);
  assert.equal(requests[0].id,requests[1].id,'same idempotency receipt');
  const claims=await Promise.all([repo.claim('interactive','one'),repo.claim('interactive','two')]);
  const lease=claims.find(Boolean)!;assert(lease);assert.equal(claims.filter(Boolean).length,1,'reserved slot has one owner');
  await db.query("UPDATE application_memberships SET active=false WHERE application_id='a' AND user_id='u'");
  assert.equal(await repo.commit(lease,result(doc)),false,'revoked initiator cannot commit');
  assert.equal((await db.query('SELECT count(*)::int n FROM requirement_documents')).rows[0].n,0);
  await db.query("UPDATE application_memberships SET active=true WHERE application_id='a' AND user_id='u'");
  await service.request('match_document.v1',doc,token());
  const expired=await repo.claim('interactive','old');assert(expired);
  await db.query("UPDATE analysis_jobs SET lease_expires_at=now()-interval '1 second' WHERE id=$1",[expired.id]);
  await repo.recover();assert.equal(await repo.commit(expired,result(doc)),false,'old fencing token rejected');
  await db.query('UPDATE analysis_jobs SET available_at=now() WHERE id=$1',[expired.id]);
  const recovered=await repo.claim('interactive','new');assert(recovered);assert.notEqual(expired.token,recovered.token);
  assert.equal(await repo.commit(recovered,result(doc)),true);assert.equal(await repo.commit(recovered,result(doc)),false,'repeat completion no-op');
  assert.equal((await db.query('SELECT count(*)::int n FROM requirement_documents WHERE unlinked_at IS NULL')).rows[0].n,1);
  assert.equal((await db.query("SELECT count(*)::int n FROM analysis_jobs WHERE task='verify_requirement.v1'")).rows[0].n,1,'aggregate job committed with link');
  const evidence=(await portal.requirement('r'))!.evidence_revision!;
  await portal.setDocumentRequirement(doc,'r',false,evidence);
  await service.request('match_document.v1',doc,token());
  const repeat=await repo.claim('interactive','repeat');assert(repeat);
  assert.equal(await repo.commit(repeat,result(doc)),true);
  assert.equal((await db.query('SELECT count(*)::int n FROM requirement_documents WHERE unlinked_at IS NULL')).rows[0].n,0,'human unlink survives rerun');
  const preference=(await service.status()).preference;
  await service.setPreference(false,preference.epoch);
  assert.equal((await service.status()).jobs.some(j=>j.state==='queued'||j.state==='running'),false,'off cancels pending jobs');
