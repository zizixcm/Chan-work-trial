  assert.equal((await lender.request('verify_requirement.v1','r',token())).id,lenderLease.id,'lender cache survives preference epochs');
  assert.equal((await db.query("SELECT count(*)::int n FROM analysis_jobs WHERE consent_scope='lender' AND lane='background'")).rows[0].n,0);
  const retry=await lender.retry(lenderLease.id,token());assert.notEqual(retry.id,lenderLease.id);
  assert.equal((await lender.get(retry.id!)).canCancel,true);
  await lender.cancel(retry.id!);
  assert.equal((await lender.get(retry.id!)).canRetry,true);
  assert.equal((await service.get(retry.id!)).canRetry,false);
  const fresh=await lender.retry(retry.id!,token());
  const revoked=await repo.claim('interactive','revoked');assert(revoked);assert.equal(revoked.id,fresh.id);
  await db.query("UPDATE application_memberships SET active=false WHERE user_id='l'");
  assert.equal(await repo.admitDispatch(revoked,DEFAULT_BUDGET),null,'revocation blocks lender dispatch');
  await db.query("UPDATE application_memberships SET active=true WHERE user_id='l'");
  await lender.retry(revoked.id,token());
  const changed=await repo.claim('interactive','changed');assert(changed);
  await db.query("UPDATE requirements SET evidence_revision=evidence_revision+1 WHERE id='r'");
  assert.equal(await repo.authorizePreparation(changed),true,'unsent draft evidence change does not stale submitted job');
  await publish();
  assert.equal(await repo.commit(changed,{model:DEFAULT_BUDGET.model,usage:{},value:verified}),false,'new submission blocks old lender commit');
